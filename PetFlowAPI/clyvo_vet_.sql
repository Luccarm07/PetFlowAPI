    v_weight pet.weight%TYPE;

BEGIN

    OPEN c_pets;

    LOOP

        FETCH c_pets INTO v_name, v_weight;

        EXIT WHEN c_pets%NOTFOUND;

        DBMS_OUTPUT.PUT_LINE(
            'Pet: ' || v_name ||
            ' | Peso: ' || v_weight
        );

    END LOOP;

    CLOSE c_pets;

END;
