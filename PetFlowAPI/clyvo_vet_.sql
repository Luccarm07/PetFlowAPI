  DBMS_OUTPUT.PUT_LINE(RPAD('-',83,'-'));

  FOR r IN c_cupons LOOP
    IF v_parceiro_atual != r.parceiro AND v_parceiro_atual != '' THEN
      DBMS_OUTPUT.PUT_LINE(RPAD(' >> Sub-Total ' || v_parceiro_atual, 40) ||
                           LPAD(v_subtotal_qtd, 8) ||
                           LPAD(TO_CHAR(v_subtotal_valor,'FM99990.00'), 15));
      DBMS_OUTPUT.PUT_LINE(RPAD('-',83,'-'));
      v_subtotal_qtd   := 0;
      v_subtotal_valor := 0;
    END IF;

    v_parceiro_atual := r.parceiro;
    v_subtotal_qtd   := v_subtotal_qtd   + r.qtd_cupons;
    v_subtotal_valor := v_subtotal_valor + r.valor_total_descontos;

    DBMS_OUTPUT.PUT_LINE(
      RPAD(r.parceiro,       25) ||
      RPAD(r.tipo_desconto,  15) ||
      LPAD(r.qtd_cupons,      8) ||
      LPAD(TO_CHAR(r.valor_total_descontos,'FM99990.00'), 15) ||
      LPAD(r.menor_custo_pts, 10) ||
      LPAD(r.maior_custo_pts, 10)
    );
  END LOOP;

  IF v_parceiro_atual != '' THEN
    DBMS_OUTPUT.PUT_LINE(RPAD(' >> Sub-Total ' || v_parceiro_atual, 40) ||
                         LPAD(v_subtotal_qtd, 8) ||
                         LPAD(TO_CHAR(v_subtotal_valor,'FM99990.00'), 15));
  END IF;
END;
