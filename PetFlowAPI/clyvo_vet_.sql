-- =============================================================
-- SECAO 6: BLOCO LAG / LEAD
-- Requisito: mostrar valor da linha anterior, atual e proxima
-- Tabela escolhida: reward_point (coluna: points)
-- =============================================================

DECLARE
  CURSOR c_lag_lead IS
    SELECT
      rp.id                                                    AS id_registro,
      t.name                                                   AS tutor,
      ra.name                                                  AS acao,
      rp.points                                                AS pts_atual,
      LAG(rp.points)  OVER (ORDER BY rp.id)                   AS pts_anterior,
      LEAD(rp.points) OVER (ORDER BY rp.id)                   AS pts_proximo
    FROM reward_point rp
    JOIN tutor        t  ON t.id  = rp.tutor_id
    JOIN reward_action ra ON ra.id = rp.reward_action_id
    ORDER BY rp.id;

  v_anterior VARCHAR2(20);
  v_proximo  VARCHAR2(20);
BEGIN
  DBMS_OUTPUT.PUT_LINE('==============================================');
  DBMS_OUTPUT.PUT_LINE('HISTORICO DE PONTOS: ANTERIOR | ATUAL | PROXIMO');
  DBMS_OUTPUT.PUT_LINE('==============================================');
  DBMS_OUTPUT.PUT_LINE(
    RPAD('ID',5) ||
    RPAD('Tutor',20) ||
    RPAD('Acao',30) ||
    LPAD('Anterior',12) ||
    LPAD('Atual',10) ||
    LPAD('Proximo',10)
  );
  DBMS_OUTPUT.PUT_LINE(RPAD('-',87,'-'));

  FOR r IN c_lag_lead LOOP
    v_anterior := CASE WHEN r.pts_anterior IS NULL THEN 'Vazio' ELSE TO_CHAR(r.pts_anterior) END;
    v_proximo  := CASE WHEN r.pts_proximo  IS NULL THEN 'Vazio' ELSE TO_CHAR(r.pts_proximo)  END;

    DBMS_OUTPUT.PUT_LINE(
      RPAD(r.id_registro, 5) ||
      RPAD(r.tutor,       20) ||
      RPAD(r.acao,        30) ||
      LPAD(v_anterior,    12) ||
      LPAD(r.pts_atual,   10) ||
      LPAD(v_proximo,     10)
    );
  END LOOP;
END;
/


