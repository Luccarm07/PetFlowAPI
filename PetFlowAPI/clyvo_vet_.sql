-- Bloco 5.1
-- Ranking de tutores por total de pontos acumulados
-- JOIN: tutor x reward_point x reward_action
-- -------------------------
DECLARE
  v_linha VARCHAR2(200);
BEGIN
  DBMS_OUTPUT.PUT_LINE('==============================================');
  DBMS_OUTPUT.PUT_LINE('RANKING DE TUTORES POR PONTOS ACUMULADOS');
  DBMS_OUTPUT.PUT_LINE('==============================================');
  DBMS_OUTPUT.PUT_LINE(RPAD('Tutor',25) || RPAD('Acoes',20) || LPAD('Total Pontos',15));
  DBMS_OUTPUT.PUT_LINE(RPAD('-',60,'-'));

  FOR r IN (
    SELECT
      t.name                       AS tutor_nome,
      COUNT(rp.id)                 AS qtd_acoes,
      SUM(rp.points)               AS total_pontos
    FROM tutor t
    JOIN reward_point rp ON rp.tutor_id = t.id
    JOIN reward_action ra ON ra.id = rp.reward_action_id
    GROUP BY t.name
    ORDER BY total_pontos DESC
  ) LOOP
    DBMS_OUTPUT.PUT_LINE(
      RPAD(r.tutor_nome, 25) ||
      RPAD(r.qtd_acoes,  20) ||
      LPAD(r.total_pontos, 15)
    );
  END LOOP;
END;
